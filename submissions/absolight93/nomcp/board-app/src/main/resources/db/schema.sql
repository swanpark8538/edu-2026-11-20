DROP TABLE IF EXISTS BOARD_FILE;
DROP TABLE IF EXISTS BOARD;
DROP TABLE IF EXISTS IDS;

-- 게시물 (과제 기본 DDL + 조회 수 / 등록·수정 일시 추가)
CREATE TABLE BOARD (
  BOARD_ID   VARCHAR(20)   NOT NULL,
  TITLE      VARCHAR(200)  NOT NULL,
  CONTENT    VARCHAR(4000),
  WRITER     VARCHAR(50)   NOT NULL,
  READCNT    INTEGER       DEFAULT 0      NOT NULL,
  CREATE_DT  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  MODIFY_DT  TIMESTAMP,
  CONSTRAINT PK_BOARD PRIMARY KEY (BOARD_ID)
);

-- 게시물 첨부파일
CREATE TABLE BOARD_FILE (
  ATCHFILE_ID    VARCHAR(30)  NOT NULL,
  BOARD_ID       VARCHAR(20)  NOT NULL,
  FILE_ORGLNM    VARCHAR(255) NOT NULL,
  FILE_STRE_NM   VARCHAR(255) NOT NULL,
  FILE_EXTSN     VARCHAR(36),
  FILE_SIZE      BIGINT       DEFAULT 0 NOT NULL,
  FILE_STRE_PATH VARCHAR(500),
  CREATE_DT      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_BOARD_FILE PRIMARY KEY (ATCHFILE_ID)
);

CREATE INDEX IDX_BOARD_FILE_01 ON BOARD_FILE (BOARD_ID);

-- eGovFrame ID Generation(EgovTableIdGnrServiceImpl) 채번 관리 테이블
CREATE TABLE IDS (
  TABLE_NAME VARCHAR(30) NOT NULL,
  NEXT_ID    INTEGER     NOT NULL,
  CONSTRAINT PK_IDS PRIMARY KEY (TABLE_NAME)
);
