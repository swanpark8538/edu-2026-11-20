DROP TABLE IF EXISTS BOARD_FILE;
DROP TABLE IF EXISTS BOARD;
DROP TABLE IF EXISTS IDS;

CREATE TABLE BOARD (
    BOARD_ID VARCHAR(20) NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    CONTENT VARCHAR(4000),
    WRITER VARCHAR(50) NOT NULL,
    REG_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (BOARD_ID)
);

CREATE TABLE BOARD_FILE (
    FILE_ID VARCHAR(20) NOT NULL,
    BOARD_ID VARCHAR(20) NOT NULL,
    FILE_SN INTEGER NOT NULL,
    ORG_FILE_NM VARCHAR(255) NOT NULL,
    SAVE_FILE_NM VARCHAR(255) NOT NULL,
    FILE_PATH VARCHAR(500) NOT NULL,
    FILE_SIZE BIGINT,
    CONTENT_TYPE VARCHAR(200),
    PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_BOARD_FILE FOREIGN KEY (BOARD_ID) REFERENCES BOARD (BOARD_ID)
);

CREATE INDEX IX_BOARD_FILE_BOARD_ID ON BOARD_FILE (BOARD_ID);

CREATE TABLE IDS (
    TABLE_NAME VARCHAR(16) NOT NULL PRIMARY KEY,
    NEXT_ID DECIMAL(30) NOT NULL
);

