-- 게시물 (TASK.md 기준 DDL + 등록일시 컬럼 추가)
CREATE TABLE BOARD (
  BOARD_ID VARCHAR(20) NOT NULL,
  TITLE    VARCHAR(200) NOT NULL,
  CONTENT  VARCHAR(4000),
  WRITER   VARCHAR(50) NOT NULL,
  REG_DT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (BOARD_ID)
);

-- 첨부파일
CREATE TABLE BOARD_FILE (
  FILE_ID       BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
  BOARD_ID      VARCHAR(20)  NOT NULL,
  ORIGINAL_NAME VARCHAR(255) NOT NULL,
  STORED_NAME   VARCHAR(100) NOT NULL,
  FILE_SIZE     BIGINT       NOT NULL,
  CONTENT_TYPE  VARCHAR(100),
  REG_DT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_BOARD_FILE_BOARD FOREIGN KEY (BOARD_ID) REFERENCES BOARD (BOARD_ID)
);

-- eGovFrame ID Generation(Table) 용 테이블
CREATE TABLE IDS (
  TABLE_NAME VARCHAR(20) NOT NULL,
  NEXT_ID    DECIMAL(30) NOT NULL,
  PRIMARY KEY (TABLE_NAME)
