-- eGovFrame 5.0 Boot 게시판 : HSQLDB 스키마
-- 과제에서 주어진 BOARD 테이블 DDL 을 기준으로 조회수와 등록일 컬럼을 추가했다.
--------------------------------------------------------------------

-- 게시물
CREATE TABLE BOARD (
    BOARD_ID VARCHAR(20)   NOT NULL,
    TITLE    VARCHAR(200)  NOT NULL,
    CONTENT  VARCHAR(4000),
    WRITER   VARCHAR(50)   NOT NULL,
    VIEW_CNT INTEGER       DEFAULT 0 NOT NULL,
    REG_DT   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MOD_DT   TIMESTAMP,
    CONSTRAINT PK_BOARD PRIMARY KEY (BOARD_ID)
);

-- 게시물 첨부파일
CREATE TABLE ATC_FILE (
    ATC_FILE_ID   VARCHAR(20)   NOT NULL,
    BOARD_ID      VARCHAR(20)   NOT NULL,
    FILE_NM       VARCHAR(255)  NOT NULL,
    STORE_FILE_NM VARCHAR(255)  NOT NULL,
    FILE_PATH     VARCHAR(1000) NOT NULL,
    FILE_SIZE     BIGINT        DEFAULT 0 NOT NULL,
    FILE_EXTSN    VARCHAR(40),
    REG_ID        VARCHAR(50),
    REG_DT        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ATC_FILE PRIMARY KEY (ATC_FILE_ID),
    CONSTRAINT FK_ATC_FILE_BOARD FOREIGN KEY (BOARD_ID) REFERENCES BOARD (BOARD_ID) ON DELETE CASCADE
);

-- 표준프레임워크 ID 발번(EgovTableIdGnrServiceImpl) 이 사용하는 번호 관리 테이블
CREATE TABLE IDS (
    TABLE_NAME VARCHAR(20) NOT NULL,
    NEXT_ID    BIGINT      NOT NULL,
    CONSTRAINT PK_IDS PRIMARY KEY (TABLE_NAME)
);

-- 목록 조회 성능을 위한 인덱스
CREATE INDEX IDX_BOARD_REG_DT ON BOARD (REG_DT);
CREATE INDEX IDX_ATC_FILE_BOARD_ID ON ATC_FILE (BOARD_ID);
