DROP TABLE BOARD_FILE IF EXISTS;
DROP TABLE BOARD IF EXISTS;
DROP TABLE IDS IF EXISTS;

CREATE MEMORY TABLE BOARD (
  BOARD_ID  VARCHAR(20)   NOT NULL,
  TITLE     VARCHAR(200)  NOT NULL,
  CONTENT   VARCHAR(4000),
  WRITER    VARCHAR(50)   NOT NULL,
  VIEW_CNT  INTEGER       DEFAULT 0 NOT NULL,
  REG_DT    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (BOARD_ID)
);

CREATE MEMORY TABLE BOARD_FILE (
  FILE_ID      VARCHAR(20)   NOT NULL,
  BOARD_ID     VARCHAR(20)   NOT NULL,
  ORIG_NAME    VARCHAR(255)  NOT NULL,
  STORED_NAME  VARCHAR(100)  NOT NULL,
  FILE_SIZE    BIGINT        NOT NULL,
  CONTENT_TYPE VARCHAR(100),
  REG_DT       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (FILE_ID),
  FOREIGN KEY (BOARD_ID) REFERENCES BOARD (BOARD_ID) ON DELETE CASCADE
);

CREATE MEMORY TABLE IDS (
  TABLE_NAME VARCHAR(16)    NOT NULL PRIMARY KEY,
  NEXT_ID    DECIMAL(30)    NOT NULL
);
