DROP TABLE BOARD IF EXISTS;
DROP TABLE ATTACH_FILE_DETAIL IF EXISTS;
DROP TABLE ATTACH_FILE IF EXISTS;
DROP TABLE IDS IF EXISTS;

-- 실행환경 ID Generation(EgovTableIdGnrServiceImpl) 채번 테이블
CREATE TABLE IDS (
  TABLE_NAME VARCHAR(20)   NOT NULL,
  NEXT_ID    DECIMAL(30,0) NOT NULL,
  PRIMARY KEY (TABLE_NAME)
);

-- 첨부파일 묶음
CREATE TABLE ATTACH_FILE (
  ATCH_FILE_ID VARCHAR(20) NOT NULL,
  CREAT_DT     TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (ATCH_FILE_ID)
);

-- 첨부파일 상세 (실제 저장 경로는 Globals.fileStorePath 기준이며 DB에는 저장 파일명만 둔다)
CREATE TABLE ATTACH_FILE_DETAIL (
  ATCH_FILE_ID   VARCHAR(20)  NOT NULL,
  FILE_SN        INTEGER      NOT NULL,
  STRE_FILE_NM   VARCHAR(64)  NOT NULL,
  ORIGNL_FILE_NM VARCHAR(255) NOT NULL,
  FILE_EXTSN     VARCHAR(20)  NOT NULL,
  FILE_SIZE      BIGINT       NOT NULL,
  CREAT_DT       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (ATCH_FILE_ID, FILE_SN),
  CONSTRAINT FK_ATTACH_FILE_DETAIL FOREIGN KEY (ATCH_FILE_ID) REFERENCES ATTACH_FILE (ATCH_FILE_ID) ON DELETE CASCADE
);

-- 게시물 (요구 DDL에 첨부파일 연결, 등록/수정 일시 컬럼을 추가)
CREATE TABLE BOARD (
  BOARD_ID     VARCHAR(20)   NOT NULL,
  TITLE        VARCHAR(200)  NOT NULL,
  CONTENT      VARCHAR(4000),
  WRITER       VARCHAR(50)   NOT NULL,
  ATCH_FILE_ID VARCHAR(20),
  REG_DT       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPD_DT       TIMESTAMP,
  PRIMARY KEY (BOARD_ID),
  CONSTRAINT FK_BOARD_ATCH_FILE FOREIGN KEY (ATCH_FILE_ID) REFERENCES ATTACH_FILE (ATCH_FILE_ID)
);

CREATE INDEX IDX_BOARD_REG_DT ON BOARD (REG_DT);
